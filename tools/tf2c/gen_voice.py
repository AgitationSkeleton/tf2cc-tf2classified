#!/usr/bin/env python3
"""Build the TF2 Classified Mercenary voice config and stage its sounds.

Source: tf2cc's voice.cfg (the Mercenary persona, the "targeted" lines other
classes say about a Mercenary). Changes for TF2 Classified (user, 2026-11-14):

* pain and death lines (_painsharp, _painsevere, _paincrticialdeath) come from the
  TF2C 4dm maps' Mercenary set instead of Open Fortress's;
* Civilian is a native TF2C class, so its tf2cc persona is not needed, but its
  "Spy!" line about a Mercenary becomes a targeted line (civilian -> mercenary).

Sounds are staged under tf2c/staging/tf2classified/sound at their tf2cc paths
(vo/custom/, vo/tf2cc/...); the 4dm pain/death files go to vo/tf2cc/tf2c/ so they
never shadow the 4dm maps' own vo/customclass/ files. Paths TF2C already ships
are refused.

  python -I tools/tf2c/gen_voice.py
Writes config/sourcemod/configs/tf2cc_tf2c/voice.cfg
"""
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import kv  # noqa: E402

SRC_CFG = os.path.join(ROOT, "config", "sourcemod", "configs", "tf2cc", "voice.cfg")
OUT_CFG = os.path.join(ROOT, "config", "sourcemod", "configs", "tf2cc_tf2c", "voice.cfg")
SOUND_ROOTS = [os.path.join(ROOT, "assets", "overrides", "tf", "sound"), os.path.join(ROOT, "assets", "tf", "sound")]
EXTRACT_VO = os.path.join(ROOT, "work", "tf2c_merc_extract", "sound", "vo", "customclass", "mercenary")
STAGE = os.path.join(ROOT, "tf2c", "staging", "tf2classified")
TF2C_LIST = os.path.join(ROOT, "work", "tf2c_research", "list_tf2c_assets.txt")
PAIN = {"_painsharp": "mercenary_painsharp", "_painsevere": "mercenary_painsevere",
        "_paincrticialdeath": "mercenary_paincrticialdeath"}


def main():
    root, _ = kv.load(SRC_CFG, "latin-1")
    src = root["tf2cc_voice"]
    stock = set(l.rsplit(" ", 1)[0].strip().lower() for l in open(TF2C_LIST, encoding="latin-1"))
    out = kv.KV()

    # targeted: stock tf2cc lines + Civilian's Mercenary callout from its old persona.
    targeted = src["targeted"]
    civ = src.get("civilian")
    civ_spy = civ.get("_spy_mercenary") if civ is not None else None
    if civ_spy is not None:
        c = kv.KV()
        merc = kv.KV()
        merc.add("cloakedspy", civ_spy)
        c.add("mercenary", merc)
        targeted.add("civilian", c)
    out.add("targeted", targeted)

    merc = src["mercenary"]
    persona = kv.KV()
    for concept, lines in merc.items():
        if concept.lower() in PAIN:
            continue
        persona.add(concept, lines)
    for concept, stem in PAIN.items():
        files = sorted(f for f in os.listdir(EXTRACT_VO) if f.lower().startswith(stem))
        lst = kv.KV()
        for i, f in enumerate(files, 1):
            lst.add(str(i), "vo/tf2cc/tf2c/" + f.lower())
        persona.add(concept, lst)
    out.add("mercenary", persona)

    # Stage every referenced sample.
    samples = set()

    def walk(node):
        for _, v in node.items():
            if isinstance(v, kv.KV):
                walk(v)
            elif re.search(r"\.(wav|mp3)$", v, re.I):
                samples.add(v)
    walk(out)
    staged, missing, refused = 0, [], []
    for s in sorted(samples):
        rel = "sound/" + s.lstrip(")^*#<>@").replace("\\", "/")
        if rel.lower() in stock:
            refused.append(rel)
            continue
        if s.startswith("vo/tf2cc/tf2c/"):
            srcf = os.path.join(EXTRACT_VO, os.path.basename(s))
        else:
            srcf = next((os.path.join(r, rel[6:]) for r in SOUND_ROOTS if os.path.exists(os.path.join(r, rel[6:]))), None)
        if not srcf or not os.path.exists(srcf):
            missing.append(rel)
            continue
        dst = os.path.join(STAGE, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(srcf, dst)
        staged += 1

    os.makedirs(os.path.dirname(OUT_CFG), exist_ok=True)
    header = ("// tf2cc for TF2 Classified: Mercenary voice (generated by tools/tf2c/gen_voice.py from\n"
              "// configs/tf2cc/voice.cfg; pain/death lines from the TF2C 4dm maps). Do not edit.\n")
    open(OUT_CFG, "w", encoding="utf-8", newline="\n").write(header + '"tf2cc_voice"\n{\n' + kv.dump(out, 1) + "}\n")
    print("voice: %d samples, staged %d, missing %d, refused (TF2C ships) %d" % (len(samples), staged, len(missing), len(refused)))
    for m in missing[:20]:
        print("  missing", m)
    for m in refused[:20]:
        print("  refused", m)


if __name__ == "__main__":
    main()
