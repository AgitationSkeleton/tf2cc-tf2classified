#!/usr/bin/env python3
"""Build everything the TF2 Classified fork ships, into tf2c/staging/tf2classified.

  python -I tools/tf2c/stage_tf2c.py [--af <April Fools custom_items_game.txt>]

Runs gen_merc_acts (player model), gen_schema (weapon schema + assets, merged
with the April Fools pack when --af is given), gen_voice (voice config + sounds),
writes config/sourcemod/configs/tf2cc_tf2c/assets.cfg (the asset paths the plugin uses
itself), gives every asset whose content changed since it was first published a new path
(version_assets.py: a client never re-downloads a path it already has), then writes
config/sourcemod/configs/tf2cc_tf2c/downloads.txt (every staged file, for the plugin's
downloads table).
"""
import argparse
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
STAGE = os.path.join(ROOT, "tf2c", "staging", "tf2classified")
DOWNLOADS = os.path.join(ROOT, "config", "sourcemod", "configs", "tf2cc_tf2c", "downloads.txt")
ASSETS = os.path.join(ROOT, "config", "sourcemod", "configs", "tf2cc_tf2c", "assets.cfg")
# Staged paths the plugin uses directly (before versioning; version_assets.py rewrites them).
PLUGIN_ASSETS = [("merc_model", "models/player/tf2cc/merc.mdl"),
                 ("bomblet_model", "models/tf2cc/of/weapons/w_models/w_grenade_bomblet.mdl"),
                 ("bond_sound", "sound/tf2cc/of/player/taunt_bond_pistol.wav"),
                 ("bouncer_sound", "sound/tf2cc/of/weapons/bouncer_nade_impact.wav")]
SKIP_EXT = (".nut",)
# Staged (FastDL keeps them, clients cache them) but not in the downloads table: kill icons no item
# uses any more (30206, the 4rdm lead pipe, was removed on 2026-11-16).
NO_DOWNLOAD = {"resource/svgs/deathnotice/tf2cc_merc_leadpipe_4rdm_v1.svg"}


def run(*args):
    subprocess.check_call([sys.executable, "-I"] + list(args))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--af")
    ap.add_argument("--refresh", action="store_true", help="rebuild deploy/fastdl_first_published.json from the FastDL history")
    a = ap.parse_args()
    run(os.path.join(HERE, "gen_merc_acts.py"))
    run(os.path.join(HERE, "gen_schema.py"), *(["--af", a.af] if a.af else []))
    run(os.path.join(HERE, "gen_voice.py"))
    lines = ["// tf2cc for TF2 Classified: staged asset paths the plugin uses (generated by tools/tf2c/stage_tf2c.py)",
             '"tf2cc_tf2c_assets"', "{"]
    for key, rel in PLUGIN_ASSETS:
        if not os.path.exists(os.path.join(STAGE, rel)):
            raise SystemExit("plugin asset %s not staged" % rel)
        lines.append('\t"%s"\t"%s"' % (key, rel[len("sound/"):] if rel.startswith("sound/") else rel))
    open(ASSETS, "w", encoding="utf-8", newline="\n").write("\n".join(lines + ["}", ""]))
    # Hand-made files staged as they are (tools/tf2c/static/<path> -> <path>): kill icons
    # (resource/svgs/deathnotice/<item_iconname>.svg, read by the client at game start).
    static = os.path.join(HERE, "static")
    for dp, _, names in os.walk(static):
        for n in names:
            rel = os.path.relpath(os.path.join(dp, n), static)
            dst = os.path.join(STAGE, rel)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copyfile(os.path.join(dp, n), dst)
    run(os.path.join(HERE, "version_assets.py"), *(["--refresh"] if a.refresh else []))
    files = []
    for dp, _, names in os.walk(STAGE):
        for n in names:
            rel = os.path.relpath(os.path.join(dp, n), STAGE).replace(os.sep, "/")
            if not rel.endswith(SKIP_EXT) and rel not in NO_DOWNLOAD:
                files.append(rel)
    files.sort()
    with open(DOWNLOADS, "w", encoding="utf-8", newline="\n") as f:
        f.write("// tf2cc for TF2 Classified: files added to the downloads table (generated by tools/tf2c/stage_tf2c.py)\n")
        f.write("\n".join(files) + "\n")
    size = sum(os.path.getsize(os.path.join(STAGE, r)) for r in files)
    print("staged %d files, %.1f MB -> %s" % (len(files), size / 1048576.0, DOWNLOADS))


if __name__ == "__main__":
    main()
